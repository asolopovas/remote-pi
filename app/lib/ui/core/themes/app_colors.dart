import 'package:flutter/material.dart';

/// Semantic color tokens for the whole app. Widgets resolve these from the active theme.
@immutable
class AppColors extends ThemeExtension<AppColors> {
  const AppColors({
    required this.bg,
    required this.surface,
    required this.border,
    required this.text,
    required this.muted,
    required this.muted2,
    required this.accent,
    required this.onAccent,
    required this.highlight,
    required this.success,
    required this.error,
    required this.warning,
    required this.working,
    required this.codeBg,
    required this.userBubble,
    required this.modelBadgeBg,
    required this.modelBadgeBorder,
    required this.denyBorder,
    required this.inputFill,
  });

  final Color bg,
      surface,
      border,
      text,
      muted,
      muted2,
      accent,
      onAccent,
      highlight,
      success,
      error,
      warning,
      working,
      codeBg,
      userBubble,
      modelBadgeBg,
      modelBadgeBorder,
      denyBorder,
      inputFill;

  static const AppColors dark = AppColors(
    bg: Color(0xFF14191F),
    surface: Color(0xFF1D252E),
    border: Color(0xFF394653),
    text: Color(0xFFF2F6FC),
    muted: Color(0xFFAEC2E0),
    muted2: Color(0xFF91A6C2),
    accent: Color(0xFF8BE9FD),
    onAccent: Color(0xFF101820),
    highlight: Color(0xFF8BE9FD),
    success: Color(0xFF50FA7B),
    error: Color(0xFFFF5555),
    warning: Color(0xFFFFB86C),
    working: Color(0xFF95CC5E),
    codeBg: Color(0xFF202832),
    userBubble: Color(0xFF25313D),
    modelBadgeBg: Color(0xFF202832),
    modelBadgeBorder: Color(0xFF394653),
    denyBorder: Color(0xFF394653),
    inputFill: Color(0xFF1D252E),
  );

  static const AppColors light = AppColors(
    bg: Color(0xFFFFFFFF),
    surface: Color(0xFFF4F4F5),
    border: Color(0xFFDADADD),
    text: Color(0xFF0A0A0A),
    muted: Color(0xFF565656),
    muted2: Color(0xFF424242),
    accent: Color(0xFF0077A3),
    onAccent: Color(0xFFFFFFFF),
    highlight: Color(0xFF005F82),
    success: Color(0xFF1E7A41),
    error: Color(0xFFC42026),
    warning: Color(0xFF9A6300),
    working: Color(0xFF426B21),
    codeBg: Color(0xFFF0F0F0),
    userBubble: Color(0xFFEAEAEC),
    modelBadgeBg: Color(0xFFEDEDEF),
    modelBadgeBorder: Color(0xFFD7D7DA),
    denyBorder: Color(0xFFC9C9CD),
    inputFill: Color(0xFFF0F0F2),
  );

  @override
  AppColors copyWith({
    Color? bg,
    Color? surface,
    Color? border,
    Color? text,
    Color? muted,
    Color? muted2,
    Color? accent,
    Color? onAccent,
    Color? highlight,
    Color? success,
    Color? error,
    Color? warning,
    Color? working,
    Color? codeBg,
    Color? userBubble,
    Color? modelBadgeBg,
    Color? modelBadgeBorder,
    Color? denyBorder,
    Color? inputFill,
  }) => AppColors(
    bg: bg ?? this.bg,
    surface: surface ?? this.surface,
    border: border ?? this.border,
    text: text ?? this.text,
    muted: muted ?? this.muted,
    muted2: muted2 ?? this.muted2,
    accent: accent ?? this.accent,
    onAccent: onAccent ?? this.onAccent,
    highlight: highlight ?? this.highlight,
    success: success ?? this.success,
    error: error ?? this.error,
    warning: warning ?? this.warning,
    working: working ?? this.working,
    codeBg: codeBg ?? this.codeBg,
    userBubble: userBubble ?? this.userBubble,
    modelBadgeBg: modelBadgeBg ?? this.modelBadgeBg,
    modelBadgeBorder: modelBadgeBorder ?? this.modelBadgeBorder,
    denyBorder: denyBorder ?? this.denyBorder,
    inputFill: inputFill ?? this.inputFill,
  );

  @override
  AppColors lerp(ThemeExtension<AppColors>? other, double t) {
    if (other is! AppColors) return this;
    Color l(Color a, Color b) => Color.lerp(a, b, t)!;
    return AppColors(
      bg: l(bg, other.bg),
      surface: l(surface, other.surface),
      border: l(border, other.border),
      text: l(text, other.text),
      muted: l(muted, other.muted),
      muted2: l(muted2, other.muted2),
      accent: l(accent, other.accent),
      onAccent: l(onAccent, other.onAccent),
      highlight: l(highlight, other.highlight),
      success: l(success, other.success),
      error: l(error, other.error),
      warning: l(warning, other.warning),
      working: l(working, other.working),
      codeBg: l(codeBg, other.codeBg),
      userBubble: l(userBubble, other.userBubble),
      modelBadgeBg: l(modelBadgeBg, other.modelBadgeBg),
      modelBadgeBorder: l(modelBadgeBorder, other.modelBadgeBorder),
      denyBorder: l(denyBorder, other.denyBorder),
      inputFill: l(inputFill, other.inputFill),
    );
  }
}
